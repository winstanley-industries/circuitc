    #[test]
    fn reserved_non_ground_alias_does_not_collapse_into_ground() {
        let mut design = voltage_divider();
        rename_net(&mut design, "GND", "REF0");
        rename_net(&mut design, "VIN", "GND");
        design.validate().expect("renamed design must be valid");
        let lowered = lower_netlist(&design);
        let ground = lowered
            .name_map
            .nets
            .iter()
            .find(|mapping| mapping.net == "REF0")
            .expect("ground mapping must exist");
        let ordinary_gnd = lowered
            .name_map
            .nets
            .iter()
            .find(|mapping| mapping.net == "GND")
            .expect("ordinary GND mapping must exist");
        assert_eq!(ground.node, "0");
        assert_ne!(ordinary_gnd.node, "0");
        assert!(ordinary_gnd.node.starts_with("CCN_"));
        assert!(
            lowered
                .netlist
                .contains(&format!("V1 {} 0 DC 10", ordinary_gnd.node))
        );
    }

