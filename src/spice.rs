    #[test]
    fn mangled_names_cannot_collide_with_preserved_source_names() {
        let mut design = voltage_divider();
        rename_net(&mut design, "VIN", "0");
        rename_net(&mut design, "VOUT", "CCN_30");
        design.validate().expect("canonical names remain valid");
        let lowered = lower_netlist(&design);
        let first = lowered
            .name_map
            .nets
            .iter()
            .find(|mapping| mapping.net == "0")
            .expect("reserved source mapping must exist");
        let second = lowered
            .name_map
            .nets
            .iter()
            .find(|mapping| mapping.net == "CCN_30")
            .expect("preserved source mapping must exist");
        assert_ne!(
            first.node.to_ascii_uppercase(),
            second.node.to_ascii_uppercase()
        );
    }

    fn rename_net(design: &mut crate::design::Design, old: &str, new: &str) {
        design
            .nets
            .iter_mut()
            .find(|net| net.name == old)
            .expect("source net must exist")
            .name = new.to_owned();
        for connection in design
            .components
            .iter_mut()
            .flat_map(|component| &mut component.connections)
        {
            if let crate::design::ConnectionState::Connected(net) = &mut connection.state
                && net == old
            {
                *net = new.to_owned();
            }
        }
        for port in design
            .modules
            .iter_mut()
            .flat_map(|module| &mut module.ports)
        {
            if let crate::design::ConnectionState::Connected(net) = &mut port.state
                && net == old
            {
                *net = new.to_owned();
            }
        }
        for route in &mut design.board.routes {
            if route.net == old {
                route.net = new.to_owned();
            }
        }
    }

